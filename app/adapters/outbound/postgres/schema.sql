-- ---------- ops: written by the agent's tools ----------

CREATE TABLE IF NOT EXISTS ops.sessions (
    session_id             uuid PRIMARY KEY,
    customer_id            text NOT NULL,
    issued_at              timestamptz NOT NULL DEFAULT now(),
    expires_at             timestamptz NOT NULL,
    step_up_at             timestamptz
);

-- Two-phase confirmation: a tool proposes, the customer confirms in the UI (never the LLM).
CREATE TABLE IF NOT EXISTS ops.pending_confirmations (
    confirmation_id        uuid PRIMARY KEY,
    session_id             uuid NOT NULL REFERENCES ops.sessions,
    action                 text NOT NULL,
    payload                jsonb NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now(),
    expires_at             timestamptz NOT NULL,
    confirmed_at           timestamptz
);

-- Khipear: one row per money movement the agent proposed, through its whole life. The customer
-- confirms with a button (never the LLM); `summary` is what that button showed them.
-- For kind pay_service the destination is a bill: destination_product_id holds its bill_id and
-- destination_customer_id the biller_id.
CREATE TABLE IF NOT EXISTS ops.transfers (
    transfer_id            uuid PRIMARY KEY,
    customer_id            text NOT NULL,
    kind                   text NOT NULL CHECK (kind IN ('own_accounts', 'pay_debt', 'third_party')),
    origin_product_id      text NOT NULL,
    destination_product_id text NOT NULL,
    destination_customer_id text NOT NULL,
    amount                 numeric(15, 2) NOT NULL CHECK (amount > 0),
    currency               text NOT NULL,
    amount_usd             numeric(15, 2),
    summary                jsonb NOT NULL,
    status                 text NOT NULL DEFAULT 'proposed'
                           CHECK (status IN ('proposed', 'executed', 'cancelled', 'expired', 'blocked')),
    status_reason          text,
    created_at             timestamptz NOT NULL DEFAULT now(),
    expires_at             timestamptz NOT NULL,
    executed_at            timestamptz,
    origin_balance_after   numeric(15, 2)
);
CREATE INDEX IF NOT EXISTS transfers_customer_day ON ops.transfers (customer_id, executed_at);

CREATE TABLE IF NOT EXISTS ops.card_actions (
    action_id              uuid PRIMARY KEY,
    product_id             text NOT NULL,
    customer_id            text NOT NULL,
    action                 text NOT NULL CHECK (action IN ('freeze', 'unfreeze', 'cancel')),
    requested_at           timestamptz NOT NULL DEFAULT now(),
    verified_at            timestamptz
);

CREATE TABLE IF NOT EXISTS ops.provisional_credits (
    credit_id              uuid PRIMARY KEY,
    idempotency_key        text NOT NULL UNIQUE,
    customer_id            text NOT NULL,
    transaction_id         text NOT NULL,
    amount                 numeric(15, 2) NOT NULL,
    currency               text NOT NULL,
    reason                 text NOT NULL,
    status                 text NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now(),
    verified_at            timestamptz
);

CREATE TABLE IF NOT EXISTS ops.disputes (
    dispute_id             uuid PRIMARY KEY,
    customer_id            text NOT NULL,
    transaction_id         text NOT NULL,
    investigation_result   jsonb NOT NULL,
    status                 text NOT NULL,
    sla_due_at             timestamptz,
    tracking_token         text UNIQUE,
    created_at             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ops.handoff_cases (
    case_id                uuid PRIMARY KEY,
    customer_id            text NOT NULL,
    dispute_id             uuid REFERENCES ops.disputes,
    priority               text NOT NULL,
    reason_codes           text[] NOT NULL,
    case_file              jsonb NOT NULL,
    status                 text NOT NULL DEFAULT 'open',
    created_at             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ops.conversations (
    conversation_id        uuid PRIMARY KEY,
    session_id             uuid REFERENCES ops.sessions,
    channel                text NOT NULL,
    language               text,
    started_at             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ops.messages (
    message_id             bigserial PRIMARY KEY,
    conversation_id        uuid NOT NULL REFERENCES ops.conversations,
    role                   text NOT NULL,
    content                text NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now()
);

-- Audit trail: every proposal, policy decision and verified outcome.
CREATE TABLE IF NOT EXISTS ops.decision_log (
    log_id                 bigserial PRIMARY KEY,
    conversation_id        uuid,
    tool                   text NOT NULL,
    proposed               jsonb NOT NULL,
    policy_decision        text NOT NULL CHECK (policy_decision IN ('allowed', 'blocked', 'needs_confirmation', 'escalated')),
    policy_reason          text,
    executed               boolean NOT NULL DEFAULT false,
    verified               boolean NOT NULL DEFAULT false,
    created_at             timestamptz NOT NULL DEFAULT now()
);

-- ---------- ops: actions the agent proposes and the customer confirms ----------
-- Every statement here is safe to run again, so it is also the migration for a database that
-- already has the rest of ops (see migrations/001_actions.sql, which must stay identical).
-- BEGIN actions migration

ALTER TABLE ops.card_actions DROP CONSTRAINT IF EXISTS card_actions_action_check;
ALTER TABLE ops.card_actions
    ADD CONSTRAINT card_actions_action_check CHECK (action IN ('freeze', 'unfreeze', 'cancel'));
CREATE INDEX IF NOT EXISTS card_actions_product_idx ON ops.card_actions (product_id, requested_at DESC);

-- One row per proposed action, grouped in a batch the customer confirms once.
CREATE TABLE IF NOT EXISTS ops.actions (
    action_id              uuid PRIMARY KEY,
    batch_id               uuid NOT NULL,
    position               integer NOT NULL,
    customer_id            text NOT NULL,
    conversation_id        text,
    action                 text NOT NULL,
    params                 jsonb NOT NULL,
    view                   jsonb NOT NULL DEFAULT '{}',
    decision               text NOT NULL CHECK (decision IN ('allowed', 'needs_confirmation', 'blocked', 'escalated')),
    reason                 text,
    status                 text NOT NULL CHECK (status IN (
        'awaiting_confirmation', 'confirmed', 'executing', 'verified', 'failed',
        'cancelled', 'expired', 'refused', 'escalated', 'skipped')),
    language               text NOT NULL DEFAULT 'es',
    idempotency_key        text NOT NULL UNIQUE,
    attempts               integer NOT NULL DEFAULT 0,
    result                 jsonb,
    created_at             timestamptz NOT NULL DEFAULT now(),
    expires_at             timestamptz NOT NULL,
    confirmed_at           timestamptz,
    finished_at            timestamptz
);
CREATE INDEX IF NOT EXISTS actions_batch_idx ON ops.actions (batch_id, position);
CREATE INDEX IF NOT EXISTS actions_customer_idx ON ops.actions (customer_id, created_at DESC);

-- What the customer chose for alerts and reminders.
CREATE TABLE IF NOT EXISTS ops.preferences (
    customer_id            text NOT NULL,
    key                    text NOT NULL,
    value                  jsonb NOT NULL,
    updated_at             timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (customer_id, key)
);

-- Messages the system sent (or tried to). `accepted` means the mail server took the message,
-- not that it reached anyone; `destination` is the registered contact, masked, and
-- `delivered_to` the demo inbox it really went to.
CREATE TABLE IF NOT EXISTS ops.outbox (
    message_id             bigserial PRIMARY KEY,
    customer_id            text NOT NULL,
    action_id              uuid,
    channel                text NOT NULL CHECK (channel IN ('email', 'sms')),
    destination            text NOT NULL,
    delivered_to           text,
    template               text NOT NULL,
    language               text NOT NULL,
    subject                text NOT NULL,
    body                   text NOT NULL,
    mode                   text NOT NULL CHECK (mode IN ('simulated', 'smtp')),
    status                 text NOT NULL CHECK (status IN ('queued', 'accepted', 'failed')),
    provider_reply         text,
    attempts               integer NOT NULL DEFAULT 0,
    created_at             timestamptz NOT NULL DEFAULT now(),
    sent_at                timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS outbox_action_idx ON ops.outbox (action_id) WHERE action_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS outbox_customer_idx ON ops.outbox (customer_id, created_at DESC);

