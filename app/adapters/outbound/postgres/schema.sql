-- Operational store for the customer-service agent.
--   core: read-mostly mirror of the bank, reloaded from silver by `python -m data_pipeline.load`
--         (which builds it as core_staging and swaps it in, so a failed load changes nothing).
--         Its only writer is khipear (postgres/transfers.py): a confirmed transfer changes two
--         balances and adds two movements, a confirmed service payment marks its bill paid, and
--         a reload puts the dataset's state back.
--   ops:  written only by the agent's tools; append-only or audited. Never reloaded.
-- Where every table comes from is in its COMMENT ('provenance: ...'). The organizer's dataset is
-- itself synthetic. Rows seeded by the team (demo scenarios) carry is_synthetic_fixture = true.

DROP SCHEMA IF EXISTS core CASCADE;
CREATE SCHEMA core;
CREATE SCHEMA IF NOT EXISTS ops;

CREATE TABLE core.customers (
    customer_id            text PRIMARY KEY,
    document_type          text,
    document_number        text,
    first_name             text,
    last_name              text,
    date_of_birth          date,
    email                  text,
    mobile_phone           text,
    city                   text,
    country                text NOT NULL,
    detected_accent        text,
    preferred_language     text NOT NULL DEFAULT 'es',
    segment                text,
    customer_status        text,
    registration_date      date,
    is_synthetic_fixture   boolean NOT NULL DEFAULT false
);
COMMENT ON TABLE core.customers IS
    'provenance: organizer dataset; preferred_language is a team assumption (es); demo rows are team fixtures';

CREATE TABLE core.products (
    product_id             text PRIMARY KEY,
    customer_id            text NOT NULL REFERENCES core.customers,
    product_type           text NOT NULL,
    product_number_last4   text,
    account_number         text,            -- savings and checking only: how a transfer names it
    currency               text,
    current_balance        numeric(15, 2),
    credit_limit           numeric(15, 2),
    product_status         text,
    interest_rate          numeric(6, 2),   -- annual %, NULL where the product has none
    opening_date           date,
    expiration_date        date,            -- cards and loans only
    days_past_due          integer,         -- credit cards and loans only
    is_synthetic_fixture   boolean NOT NULL DEFAULT false
);
CREATE INDEX ON core.products (customer_id);
CREATE INDEX ON core.products (account_number);
COMMENT ON TABLE core.products IS
    'provenance: organizer dataset; demo rows are team fixtures';

CREATE TABLE core.transactions (
    transaction_id         text PRIMARY KEY,
    customer_id            text NOT NULL REFERENCES core.customers,
    product_id             text,
    transaction_date       timestamp NOT NULL,
    transaction_type       text,
    transaction_category   text,
    amount                 numeric(15, 2) NOT NULL,
    currency               text NOT NULL,
    amount_usd             numeric(15, 2),
    channel                text,
    merchant_name          text,
    transaction_country    text,
    transaction_city       text,
    transaction_status     text NOT NULL,
    response_code          text,
    is_fraud               boolean,
    fraud_score            numeric(5, 2),
    is_synthetic_fixture   boolean NOT NULL DEFAULT false
);
CREATE INDEX ON core.transactions (customer_id, transaction_date DESC);
CREATE INDEX ON core.transactions (transaction_date);  -- the dataset's last day, for every window
COMMENT ON TABLE core.transactions IS
    'provenance: organizer dataset, transaction_category completed from the merchant in silver; demo rows are team fixtures';

-- Statement and payment schedule of every credit card and loan. The organizer's data has no due
-- dates, statements or installments: these are generated by a fixed rule in data_pipeline/load.py
-- from the product's balance, rate and days_past_due, as of the dataset's last day.
CREATE TABLE core.billing (
    product_id             text PRIMARY KEY REFERENCES core.products,
    customer_id            text NOT NULL REFERENCES core.customers,
    as_of                  date NOT NULL,
    statement_date         date NOT NULL,
    due_date               date NOT NULL,
    statement_balance      numeric(15, 2),          -- cards only
    minimum_payment        numeric(15, 2) NOT NULL, -- cards: minimum due; loans: installment
    past_due_amount        numeric(15, 2) NOT NULL,
    remaining_installments integer,                 -- loans only
    provenance             text NOT NULL DEFAULT 'team_generated'
);
CREATE INDEX ON core.billing (customer_id);
COMMENT ON TABLE core.billing IS
    'provenance: team-generated by a deterministic rule over organizer products (illustrative, not bank records)';

